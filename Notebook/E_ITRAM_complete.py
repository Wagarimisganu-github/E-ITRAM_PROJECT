def clean_name(filename):
    """
    Convert technical filenames into publication-style titles.
    """
    name = Path(filename).stem

    replacements = {
        "_": " ",
        "-": " ",
        "EITRAM": "E-ITRAM",
        "eitram": "E-ITRAM",
        "ROC": "ROC",
        "PR": "PR",
        "SHAP": "SHAP",
        "LIME": "LIME",
        "KRI": "KRI",
        "McNemar": "McNemar",
    }

    for old, new in replacements.items():
        name = name.replace(old, new)

    name = re.sub(r"\s+", " ", name).strip()

    return name


