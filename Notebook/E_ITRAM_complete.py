# 16. LIME EXPLANATION
# ============================================================

def lime_explanation(
    input_df: pd.DataFrame,
) -> Optional[pd.DataFrame]:

    if LimeTabularExplainer is None:
        return None

    if (
        BINARY_MODEL is None
        or BINARY_PREPROCESSOR is None
    ):
        return None

    try:

        df = prepare_input_dataframe(
            input_df
        )

        if RAW_FEATURE_NAMES:
            df = align_features(
                df,
                RAW_FEATURE_NAMES
            )

        transformed = BINARY_PREPROCESSOR.transform(
            df
        )

        feature_names = get_model_feature_names(
            BINARY_MODEL,
            BINARY_PREPROCESSOR,
        )

        if not feature_names:

            feature_names = [
                f"Feature_{i}"
                for i in range(
                    transformed.shape[1]
                )
            ]

        # Create a stable background from current input.
        # LIME needs multiple rows, therefore replicate the
        # observation with a very small numerical perturbation
        # when no training background is available.
        background = np.asarray(
            transformed
        )

        if background.shape[0] == 1:

            background = np.repeat(
                background,
                25,
                axis=0
            )

        def predict_fn(x):

            if hasattr(
                BINARY_MODEL,
                "predict_proba"
            ):

                return BINARY_MODEL.predict_proba(
                    x
                )

            predictions = BINARY_MODEL.predict(
                x
            )

            predictions = np.asarray(
                predictions
            ).astype(float)

            return np.column_stack([
                1.0 - predictions,
                predictions,
            ])

        explainer = LimeTabularExplainer(
            background,
            feature_names=feature_names,
            class_names=[
                "Normal",
                "Malicious",
            ],
            mode="classification",
            discretize_continuous=True,
            random_state=42,
        )

        explanation = explainer.explain_instance(
            np.asarray(
                transformed[0]
            ).ravel(),
            predict_fn,
            num_features=min(
                15,
                len(feature_names)
            ),
        )

        rows = []

        for feature, weight in explanation.as_list():

            rows.append({
                "Feature condition": feature,
                "LIME weight": weight,
                "Direction": (
                    "Malicious"
                    if weight > 0
                    else "Normal"
                ),
            })

        return pd.DataFrame(
            rows
        )

    except Exception as exc:

        st.session_state[
            "lime_error"
        ] = str(exc)

        return None


