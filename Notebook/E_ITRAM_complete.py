def figure_sort_key(path):
    """
    Prefer numerical figure ordering when filenames contain
    figure numbers.
    """

    name = path.stem.lower()

    match = re.search(
        r"(?:figure|fig)[_\-\s]*(\d+)",
        name
    )

    if match:
        return (
            0,
            int(match.group(1)),
            name
        )

    # Architecture first
    if "architecture" in name:
        return (0, 0, name)

    # Then alphabetically
    return (1, 9999, name)


