# 12. BINARY PREDICTION
# ============================================================

def binary_predict(
    input_df: pd.DataFrame
) -> Tuple[np.ndarray, np.ndarray]:

    if BINARY_MODEL is None:
        raise RuntimeError(
            "Binary model is not available."
        )

    if BINARY_PREPROCESSOR is None:
        raise RuntimeError(
            "Binary preprocessing pipeline is not available."
        )

    df = prepare_input_dataframe(input_df)

    raw_names = RAW_FEATURE_NAMES

    if raw_names:
        df = align_features(
            df,
            raw_names
        )

    transformed = BINARY_PREPROCESSOR.transform(df)

    predictions = BINARY_MODEL.predict(
        transformed
    )

    if hasattr(
        BINARY_MODEL,
        "predict_proba"
    ):

        probabilities = BINARY_MODEL.predict_proba(
            transformed
        )

        if probabilities.ndim == 2 and probabilities.shape[1] >= 2:
            malicious_probability = probabilities[:, 1]

        else:
            malicious_probability = probabilities.ravel()

    elif hasattr(
        BINARY_MODEL,
        "decision_function"
    ):

        decision = BINARY_MODEL.decision_function(
            transformed
        )

        malicious_probability = 1.0 / (
            1.0 + np.exp(-np.asarray(decision))
        )

    else:

        malicious_probability = np.asarray(
            predictions,
            dtype=float
        )

    return (
        np.asarray(predictions),
        np.asarray(malicious_probability),
    )


# ============================================================
# 13. MULTICLASS ATTACK CATEGORY PREDICTION
# ============================================================

def multiclass_predict(
    input_df: pd.DataFrame
) -> Tuple[Optional[np.ndarray], Optional[np.ndarray]]:

    if (
        MULTICLASS_MODEL is None
        or MULTICLASS_PREPROCESSOR is None
    ):
        return None, None

    df = prepare_input_dataframe(input_df)

    raw_names = RAW_FEATURE_NAMES

    if raw_names:
        df = align_features(
            df,
            raw_names
        )

    transformed = MULTICLASS_PREPROCESSOR.transform(
        df
    )

    predictions = MULTICLASS_MODEL.predict(
        transformed
    )

    probabilities = None

    if hasattr(
        MULTICLASS_MODEL,
        "predict_proba"
    ):

        probabilities = MULTICLASS_MODEL.predict_proba(
            transformed
        )

    labels = predictions

    if LABEL_ENCODER is not None:

        try:

            labels = LABEL_ENCODER.inverse_transform(
                np.asarray(predictions).astype(int)
            )

        except Exception:
            labels = predictions

    return (
        np.asarray(labels),
        probabilities,
    )


# ============================================================
# 14. RISK TRANSLATION
# ============================================================

def calculate_risk(
    malicious_probability: float,
    impact_factor: float,
) -> Dict[str, Any]:

    probability = normalize_probability(
        malicious_probability
    )

    impact = safe_float(
        impact_factor,
        1.0
    )

    impact = float(
        np.clip(
            impact,
            0.0,
            1.0
        )
    )

    risk_score = 100.0 * probability * impact

    risk_score = float(
        np.clip(
            risk_score,
            0.0,
            100.0
        )
    )

    band = risk_band(
        risk_score
    )

    exceeds_appetite = (
        risk_score >= RISK_THRESHOLD
    )

    return {
        "likelihood": probability,
        "impact": impact,
        "risk_score": risk_score,
        "risk_band": band,
        "exceeds_appetite": exceeds_appetite,
    }


# ============================================================
# 15. SHAP EXPLANATION
# ============================================================

def shap_explanation(
    input_df: pd.DataFrame,
    max_features: int = 15,
) -> Optional[pd.DataFrame]:

    if shap is None:
        return None

    if (
        BINARY_MODEL is None
        or BINARY_PREPROCESSOR is None
    ):
        return None

    try:

        df = prepare_input_dataframe(
            input_df
        )

        if RAW_FEATURE_NAMES:
            df = align_features(
                df,
                RAW_FEATURE_NAMES
            )

        transformed = BINARY_PREPROCESSOR.transform(
            df
        )

        feature_names = get_model_feature_names(
            BINARY_MODEL,
            BINARY_PREPROCESSOR,
        )

        if not feature_names:

            feature_names = [
                f"Feature_{i}"
                for i in range(
                    transformed.shape[1]
                )
            ]

        # Limit explanation to first observation
        x = transformed[:1]

        # Linear model
        if hasattr(
            BINARY_MODEL,
            "coef_"
        ):

            explainer = shap.LinearExplainer(
                BINARY_MODEL,
                transformed[:min(
                    100,
                    transformed.shape[0]
                )],
            )

            shap_values = explainer.shap_values(
                x
            )

            if isinstance(
                shap_values,
                list
            ):
                values = np.asarray(
                    shap_values[-1]
                ).reshape(-1)

            else:
                values = np.asarray(
                    shap_values
                ).reshape(-1)

        else:

            explainer = shap.TreeExplainer(
                BINARY_MODEL
            )

            shap_values = explainer.shap_values(
                x
            )

            if isinstance(
                shap_values,
                list
            ):

                values = np.asarray(
                    shap_values[-1]
                ).reshape(-1)

            else:

                values = np.asarray(
                    shap_values
                )

                if values.ndim == 3:
                    values = values[0, :, -1]

                else:
                    values = values.reshape(-1)

        n = min(
            len(feature_names),
            len(values)
        )

        result = pd.DataFrame({
            "Feature": feature_names[:n],
            "SHAP value": values[:n],
        })

        result["Absolute SHAP"] = (
            result["SHAP value"]
            .abs()
        )

        result = result.sort_values(
            "Absolute SHAP",
            ascending=False
        ).head(
            max_features
        )

        result["Direction"] = np.where(
            result["SHAP value"] >= 0,
            "Increases malicious prediction",
            "Decreases malicious prediction",
        )

        return result.reset_index(
            drop=True
        )

    except Exception as exc:

        st.session_state[
            "shap_error"
        ] = str(exc)

        return None


